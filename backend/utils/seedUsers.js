require("dotenv").config();
const mongoose = require("mongoose");
const connectDB = require("../config/db");
const User = require("../models/User");
const Post = require("../models/Post");

const USER_COUNT = 200;
const SKILL_POOL = [
  "React", "Node.js", "MongoDB", "TypeScript", "Python", "Go",
  "Docker", "GraphQL", "AWS", "Next.js", "Vue", "Rust",
];
const SAMPLE_POSTS = [
  "Just shipped a new feature using Socket.io for real-time updates!",
  "Anyone got tips for optimizing MongoDB aggregation pipelines?",
  "React Server Components finally clicked for me today.",
  "Deployed my first app on Render — CI/CD pipeline was easier than I expected.",
  "Looking for a study buddy to work through system design problems.",
];

const randomFrom = (arr, n = 1) =>
  [...arr].sort(() => 0.5 - Math.random()).slice(0, n);

async function seed() {
  await connectDB();

  const createdUsers = [];
  for (let i = 1; i <= USER_COUNT; i++) {
    const email = `devuser${i}@devconnect.test`;
    const exists = await User.findOne({ email });
    if (exists) {
      createdUsers.push(exists);
      continue;
    }

    const user = await User.create({
      name: `Dev User ${i}`,
      email,
      password: "Password123", // hashed automatically by the User model
      bio: "Sample account generated by the seed script.",
      skills: randomFrom(SKILL_POOL, 3),
    });
    createdUsers.push(user);
  }

  // A handful of sample posts so the feed isn't empty.
  for (let i = 0; i < 20; i++) {
    const author = createdUsers[Math.floor(Math.random() * createdUsers.length)];
    await Post.create({
      author: author._id,
      content: SAMPLE_POSTS[i % SAMPLE_POSTS.length],
      tags: randomFrom(SKILL_POOL, 2),
    });
  }

  console.log(`Seed complete: ${createdUsers.length} users, 20 sample posts.`);
  await mongoose.disconnect();
}

seed().catch((err) => {
  console.error("Seed failed:", err);
  process.exit(1);
});
